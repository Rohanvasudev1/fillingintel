"""The README's generated blocks (Step 14 ticket 03).

``README.md`` holds two blocks between marker comments, rewritten in place by
``python -m eval.results_table`` and compared by ``--check``; the prose around
them is the author's and is never touched.  Both blocks read the same committed
files as ``benchmarks/results.md``.
"""
from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

from eval.readme_headline import headline_block
from eval.readme_numbers import numbers_block
from eval.results_inputs import ROUTER_ROWS, TEST_ROUTER_RUNS, TEST_RUNS, RunNames
from eval.results_sources import ResultsInputError, load_router_split, load_split
from ingest.provenance import REPO_ROOT
from retrieve.routing_maps import PRE_REGISTERED

README = "README.md"
HEADLINE, NUMBERS = "test-headline", "unpublished-numbers"
BLOCKS = (HEADLINE, NUMBERS)
_NOTE = "generated by python -m eval.results_table; edit the code, not this block"


class ReadmeMarkerError(ResultsInputError):
    """The README lacks a block's markers, repeats them, or has them out of order."""


def begin_marker(name: str) -> str:
    return f"<!-- BEGIN {name}: {_NOTE} -->"


def end_marker(name: str) -> str:
    return f"<!-- END {name} -->"


def splice(text: str, blocks: Mapping[str, str]) -> str:
    """*text* with each block's lines between its markers replaced by *blocks[name]*."""
    for name, body in blocks.items():
        begin, end = begin_marker(name), end_marker(name)
        if text.count(begin) != 1 or text.count(end) != 1:
            raise ReadmeMarkerError(f"{README} needs exactly one '{begin}' and one '{end}'")
        start, stop = text.index(begin) + len(begin), text.index(end)
        if stop < start:
            raise ReadmeMarkerError(f"{README}: the end marker of {name} comes first")
        text = f"{text[:start]}\n{body}{text[stop:]}"
    return text


def readme_blocks(root: Path = REPO_ROOT, test_runs: RunNames = TEST_RUNS,
                  test_router_runs: RunNames = TEST_ROUTER_RUNS) -> dict[str, str]:
    test = load_split(test_runs, root)
    routers = load_router_split(test_router_runs, ROUTER_ROWS, root)
    pre = routers[ROUTER_ROWS[PRE_REGISTERED]].full_files()
    if len(pre) != 1:
        raise ResultsInputError("the README needs exactly one pre-registered router test run")
    return {HEADLINE: _text(headline_block({**test, **routers})),
            NUMBERS: _text(numbers_block(pre[0], root))}


def _text(lines: list[str]) -> str:
    return "\n".join(lines).rstrip("\n") + "\n"
